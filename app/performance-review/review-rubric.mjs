export function isReviewLevel(value) {
  return typeof value === 'string' && Object.hasOwn(REVIEW_LEVEL_LABELS, value)
}

export function getReviewRubric(level) {
  if (!isReviewLevel(level)) throw new Error('Unknown performance review level')
  const order = Object.keys(REVIEW_LEVEL_LABELS)
  const nextLevel = order[order.indexOf(level) + 1] ?? null
  return {
    version: REVIEW_RUBRIC_VERSION,
    level,
    label: REVIEW_LEVEL_LABELS[level],
    source: level === 'junior' ? 'working_guidance' : 'pdf',
    nextLevel,
    nextLevelLabel: nextLevel === null ? null : REVIEW_LEVEL_LABELS[nextLevel],
    competencies: competencies.map(({ id, title, levels }) => ({
      id,
      title,
      criteria: levels[level],
      nextCriteria: nextLevel === null ? [] : levels[nextLevel],
    })),
  }
}
