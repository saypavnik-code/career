export function getArea(areaId) {
  return COMPETENCY_SCALE.find((a) => a.id === areaId);
}

export function getAllCriteria() {
  return COMPETENCY_SCALE.flatMap((area) =>
    LEVELS.flatMap((level) => area.levels[level].map((c) => ({ ...c, areaId: area.id, areaName: area.name, level })))
  );
}

export function getCriterion(criterionId) {
  return getAllCriteria().find((c) => c.id === criterionId);
}
