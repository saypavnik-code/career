// =========================================================
// DOMAIN RULES — сопоставление Activity с пунктами компетенций
// Чистая функция: находит потенциальные "доказательства" выполнения
// пункта шкалы компетенций среди уже зафиксированных активностей.
// Работает по пересечению ключевых слов — не идеально, но даёт
// пользователю быструю подсказку вместо ручного перебора всех активностей.
// =========================================================

const STOP_WORDS = new Set([
  'и', 'в', 'на', 'с', 'по', 'для', 'от', 'из', 'к', 'а', 'но', 'или', 'не',
  'что', 'как', 'это', 'его', 'её', 'их', 'при', 'за', 'до', 'же', 'то',
]);

// Грубый стеммер для русского: отсекает частые окончания существительных/
// глаголов/прилагательных, чтобы "анализирует"/"анализ", "конкурентную"/
// "конкурентный" схлопывались в одну основу. Не претендует на лингвистическую
// точность — достаточно для эвристики подсказок, не для финального решения.
const SUFFIXES = [
  'ированию', 'ированием', 'ированного', 'ирования', 'ировать', 'ированы',
  'ированный', 'ированная', 'ированное', 'ировал', 'ирует', 'ируют',
  'ования', 'ование', 'ований',
  'ями', 'ами', 'ыми', 'ими', 'его', 'ого', 'ему', 'ому', 'ыми',
  'ает', 'яет', 'ует', 'ют', 'ит', 'ат', 'ят',
  'ную', 'ного', 'ному', 'ной', 'ные', 'ных', 'ным',
  'ция', 'ции', 'ций',
  'ами', 'ями', 'ов', 'ев', 'ей', 'ой', 'ый', 'ий', 'ая', 'яя', 'ое', 'ее',
  'ла', 'ло', 'ли', 'л', 'а', 'я', 'ы', 'и', 'у', 'ю', 'е',
];

function stem(word) {
  for (const suf of SUFFIXES) {
    if (word.length > suf.length + 3 && word.endsWith(suf)) {
      return word.slice(0, -suf.length);
    }
  }
  return word;
}

function extractKeywords(text) {
  return text
    .toLowerCase()
    .replace(/[.,;:()«»"'!?—–]/g, ' ')
    .split(/\s+/)
    .filter((w) => w.length > 3 && !STOP_WORDS.has(w))
    .map(stem);
}

/**
 * Возвращает список активностей, чьи описание/теги пересекаются
 * с ключевыми словами текста пункта компетенции — как кандидаты
 * на "доказательство" выполнения. Сравнение идёт по грубым основам
 * слов (см. stem()), чтобы формы одного корня считались совпадением.
 */
export function findPotentialEvidence(criterionText, activities, { minMatches = 2 } = {}) {
  const criterionStems = new Set(extractKeywords(criterionText));
  if (criterionStems.size === 0) return [];

  const scored = activities.map((activity) => {
    const activityText = [activity.description, ...(activity.tags || [])].join(' ');
    const activityStems = extractKeywords(activityText);
    const matches = activityStems.filter((w) => criterionStems.has(w));
    return { activity, matchCount: matches.length };
  });

  return scored
    .filter((s) => s.matchCount >= minMatches)
    .sort((a, b) => b.matchCount - a.matchCount)
    .map((s) => s.activity);
}
